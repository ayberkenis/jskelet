/**
 * `src/templates/layout.jsk` → `src/templates/layout.render.js`.
 *
 * Framework varsayılan layout'u uygulama `.jskelet/templates` manifest'ine
 * girmez; runtime doğrudan bu modülü import eder. Kaynak değişince:
 *
 *   node scripts/compile-framework-layout.mjs
 *
 * `--check` ile CI drift doğrulaması: çıktı disktekine eşit değilse exit 1.
 */
import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";
import { compileSource } from "../src/compile/index.js";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SRC = path.join(ROOT, "src", "templates", "layout.jsk");
const OUT = path.join(ROOT, "src", "templates", "layout.render.js");

const source = fs.readFileSync(SRC, "utf8");
const { code } = compileSource(source, {
  viewId: "layout",
  file: "src/templates/layout.jsk",
  knownComponents: new Set([
    "Link",
    "Image",
    "Icon",
    "CsrfField",
    "PreloadImage",
    "Stylesheets",
    "BodyScripts",
    "JsonLd",
  ]),
});

const banner =
  "/** @generated by scripts/compile-framework-layout.mjs — do not edit */\n";
const next = banner + code.replace(/^\/\*\* @generated by jskelet — do not edit \*\/\n/, "");

const check = process.argv.includes("--check");
if (check) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
  if (current !== next) {
    console.error(
      "[compile-framework-layout] layout.render.js is out of date — run: node scripts/compile-framework-layout.mjs",
    );
    process.exit(1);
  }
  console.log("layout.render.js up to date");
  process.exit(0);
}

fs.writeFileSync(OUT, next, "utf8");
console.log(`wrote ${path.relative(ROOT, OUT)}`);
